# shellcheck shell=bash
# kitty support: colors that follow light/dark mode, an iglass settings file, one include line.
#
# kitty reads one kitty.conf, from the first of these directories that has a kitty.conf and is
# writable: $KITTY_CONFIG_DIRECTORY (always used when set), $XDG_CONFIG_HOME/kitty,
# ~/.config/kitty, ~/Library/Preferences/kitty (macOS), $XDG_CONFIG_DIRS/…/kitty; otherwise
# ~/.config/kitty. In that directory iglass writes:
#   iglass.conf                       opacity, blur, padding, cursor, font; colors for kitty < 0.38
#   dark-theme.auto.conf, light-theme.auto.conf, no-preference-theme.auto.conf
#                                     the colors kitty 0.38+ switches between with the system
# and adds two lines (a comment and `include <dir>/iglass.conf`) to the end of kitty.conf.
# A user's own *-theme.auto.conf files are moved aside and put back on uninstall.

KITTY_BUNDLE_ID="net.kovidgoyal.kitty"
KITTY_MARKER="# Added by iglass (https://github.com/vukkt/iglass). Remove with: iglass uninstall"
KITTY_GEN_MARKER="# Generated by iglass"
KITTY_THEME_FILES="dark-theme.auto.conf light-theme.auto.conf no-preference-theme.auto.conf"
IGLASS_MIN_KITTY_AUTO="0.38.0" # first release that switches colors with the system

# The directory kitty reads its configuration from, chosen exactly the way kitty does.
kitty_config_dir() {
  if [[ -n "${KITTY_CONFIG_DIRECTORY:-}" ]]; then
    printf '%s\n' "${KITTY_CONFIG_DIRECTORY/#\~/$HOME}"
    return
  fi
  local b bases=()
  [[ -n "${XDG_CONFIG_HOME:-}" ]] && bases+=("$XDG_CONFIG_HOME")
  bases+=("$HOME/.config")
  is_macos && bases+=("$HOME/Library/Preferences")
  if [[ -n "${XDG_CONFIG_DIRS:-}" ]]; then
    local more=()
    IFS=: read -r -a more <<<"$XDG_CONFIG_DIRS"
    bases+=(${more[@]+"${more[@]}"})
  fi
  for b in "${bases[@]}"; do
    if [[ -e "$b/kitty/kitty.conf" && -w "$b/kitty" ]]; then
      printf '%s/kitty\n' "$b"
      return
    fi
  done
  printf '%s/kitty\n' "${XDG_CONFIG_HOME:-$HOME/.config}"
}
kitty_conf() { printf '%s/kitty.conf\n' "$(kitty_config_dir)"; }
kitty_iglass_file() { printf '%s/iglass.conf\n' "$(kitty_config_dir)"; }
kitty_include_line() { printf 'include %s\n' "$(kitty_iglass_file)"; }

# Print the path of kitty.app (macOS only).
kitty_app_path() {
  is_macos || return 0
  if [[ -n "${IGLASS_KITTY_APP:-}" ]]; then
    [[ -d "$IGLASS_KITTY_APP" ]] && printf '%s\n' "$IGLASS_KITTY_APP"
    return 0
  fi
  local candidate
  for candidate in "/Applications/kitty.app" "$HOME/Applications/kitty.app"; do
    if [[ -d "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  candidate=$(mdfind "kMDItemCFBundleIdentifier == '$KITTY_BUNDLE_ID'" 2>/dev/null | head -n 1)
  [[ -n "$candidate" && -d "$candidate" ]] && printf '%s\n' "$candidate"
  return 0
}

# Print the path of the kitty executable, or nothing if kitty is not installed.
kitty_bin() {
  if [[ -n "${IGLASS_KITTY_BIN:-}" ]]; then
    [[ -x "$IGLASS_KITTY_BIN" ]] && printf '%s\n' "$IGLASS_KITTY_BIN"
    return 0
  fi
  local app
  if is_macos; then
    app=$(kitty_app_path)
    [[ -n "$app" && -x "$app/Contents/MacOS/kitty" ]] && printf '%s\n' "$app/Contents/MacOS/kitty"
    return 0
  fi
  if command -v kitty >/dev/null 2>&1; then
    command -v kitty
  elif [[ -x "$HOME/.local/kitty.app/bin/kitty" ]]; then # kitty's own installer
    printf '%s\n' "$HOME/.local/kitty.app/bin/kitty"
  fi
  return 0
}

kitty_present() { [[ -n "$(kitty_bin)" ]]; }
kitty_running() { proc_running kitty; }

# Print kitty's version (e.g. 0.49.2), from "kitty 0.49.2 created by Kovid Goyal".
kitty_version() {
  local bin
  bin=$(kitty_bin)
  [[ -n "$bin" ]] || return 0
  "$bin" --version 2>/dev/null | sed -n '1s/^kitty \([0-9][0-9.]*\).*/\1/p'
}

kitty_auto_themes_supported() {
  local v
  v=$(kitty_version)
  [[ -z "$v" ]] || version_ge "$v" "$IGLASS_MIN_KITTY_AUTO"
}

# kitty_validate FILE… — load each file with kitty's own config parser. kitty has no validator
# command, so this is exactly what kitty runs at startup: unknown options are reported as
# "Ignoring …" and bad values raise an error. Prints kitty's messages on failure. Skipped
# without kitty.
kitty_validate() {
  local bin out
  bin=$(kitty_bin)
  [[ -n "$bin" ]] || return 0
  if ! out=$("$bin" +runpy 'import sys
from kitty.config import load_config
for path in sys.argv[1:]:
    load_config(path)' "$@" 2>&1) || [[ -n "$out" ]]; then
    printf '%s\n' "$out" >&2
    return 1
  fi
}

# kitty_colors OPTIONS_JSON MODE TITLE — print a colors file.
kitty_colors() {
  jq -nj --slurpfile palette "$IGLASS_PALETTE" --argjson o "$1" --arg mode "$2" --arg title "$3" \
    -f "$IGLASS_ROOT/lib/kitty.jq"
}

# kitty_glass OPTIONS_JSON — print "OPACITY BLUR" for the chosen variant or custom settings.
kitty_glass() {
  jq -nr --slurpfile palette "$IGLASS_PALETTE" --argjson o "$1" '
    $palette[0] as $p
    | (if $o.custom then $p.variants[$o.custom.base] + $o.custom.overrides else $p.variants[$o.variant] end) as $v
    | "\(((1 - $v.transparency) * 100 | round) / 100) \(if ($v.blur | not) or $v.blurRadius == 0 then 0 else $v.blurRadius end)"'
}

# kitty_settings OPTIONS_JSON — print iglass.conf.
kitty_settings() {
  local opts=$1 opacity blur fallback
  read -r opacity blur <<<"$(kitty_glass "$opts")"
  fallback=$(jq -r 'if (.appearance // "auto") == "auto" then "dark" else .appearance end' <<<"$opts")
  jq -nr --argjson o "$opts" --arg opacity "$opacity" --arg blur "$blur" '
    [
      "# Generated by iglass \($o.version) (https://github.com/vukkt/iglass): settings for kitty.",
      "# `iglass install` rewrites this file; `iglass uninstall` removes it.",
      "# The colors switch with light and dark mode through the *-theme.auto.conf files next to",
      "# this one (kitty 0.38+). The colors below are for earlier versions.",
      "background_opacity \($opacity)",
      "background_blur \($blur)",
      "window_padding_width 10 12"
    ]
    + (if $o.cursor == "keep" then []
       else ["cursor_shape \({"bar": "beam", "box": "block", "underline": "underline"}[$o.cursor])"] end)
    + (if $o.window == "no-titlebar" then ["hide_window_decorations titlebar-only"]
       elif $o.window == "native" then ["wayland_titlebar_color background"] else [] end)
    + (if $o.fontFamily then ["font_family \($o.fontFamily)", "font_size \($o.fontSize)"] else [] end)
    | join("\n")'
  printf '\n'
  kitty_colors "$opts" "$fallback" "Colors for kitty before 0.38"
}

# The colors file for each theme file kitty switches between. A pinned appearance
# (--appearance dark|light) puts the same colors in all three.
kitty_theme_mode() { # OPTIONS_JSON THEME_FILE
  local pinned
  pinned=$(jq -r '.appearance // "auto"' <<<"$1")
  if [[ "$pinned" != auto ]]; then
    printf '%s\n' "$pinned"
  elif [[ "$2" == dark-theme.auto.conf ]]; then
    printf 'dark\n'
  else
    printf 'light\n' # light, and no-preference (what GNOME reports in light mode)
  fi
}

# kitty_export_dir OPTIONS_JSON DIR — write iglass.conf and the three theme files into DIR.
kitty_export_dir() {
  local opts=$1 dir=$2 f mode
  mkdir -p "$dir"
  kitty_settings "$opts" >"$dir/iglass.conf"
  for f in $KITTY_THEME_FILES; do
    mode=$(kitty_theme_mode "$opts" "$f")
    kitty_colors "$opts" "$mode" "iglass colors for kitty: ${f%%-theme.auto.conf} system appearance → iglass $mode" >"$dir/$f"
  done
}

kitty_is_ours() { [[ -f "$1" ]] && grep -q "^$KITTY_GEN_MARKER" "$1"; }

# kitty_install OPTIONS_JSON
kitty_install() {
  local opts=$1 dir target work f saved created=false verb=Installed look backups files
  [[ -n "$(state_get '.kitty.installedAt')" ]] && verb=Updated
  dir=$(kitty_config_dir)
  target="$dir/kitty.conf"
  mkdir -p "$IGLASS_STATE_DIR"
  work=$(mktemp -d "$IGLASS_STATE_DIR/.kitty.XXXXXX") || die "Could not create a temporary folder."
  kitty_export_dir "$opts" "$work"
  files=("$work/iglass.conf")
  for f in $KITTY_THEME_FILES; do files+=("$work/$f"); done
  if ! kitty_validate "${files[@]}"; then
    rm -rf "$work"
    die "Internal error: kitty rejected the generated settings. Nothing was changed." \
      "Please report this at https://github.com/vukkt/iglass/issues"
  fi
  mkdir -p "$dir" || die "Could not create $dir."

  # A user's own light/dark theme files would override iglass's colors: set them aside, once.
  backups="$IGLASS_STATE_DIR/backups/kitty-themes"
  saved=$(state_get '.kitty.savedThemes // [] | join(" ")')
  for f in $KITTY_THEME_FILES; do
    if [[ -e "$dir/$f" ]] && ! kitty_is_ours "$dir/$f"; then
      mkdir -p "$backups"
      if [[ -e "$backups/$f" ]]; then # made after iglass was installed; keep it too
        mv -f "$dir/$f" "$backups/$f.newer-$(date +%Y%m%d%H%M%S)"
        ui_warn "Moved your newer kitty $f aside to $backups (your original is restored on uninstall)."
      else
        mv -f "$dir/$f" "$backups/$f"
        saved="$saved $f"
      fi
    fi
  done
  for f in iglass.conf $KITTY_THEME_FILES; do
    mv -f "$work/$f" "$dir/$f"
  done
  rm -rf "$work"

  [[ -e "$target" ]] || created=true
  look=$(jq -r 'if (.appearance // "auto") == "auto" then "light and dark, " else "" end' <<<"$opts") # pinned: in the summary
  if configfile_add_include "$target" "$KITTY_MARKER" "$(kitty_include_line)" kitty-config-before-iglass; then
    state_update '.kitty = {version: $v, installedAt: $t, options: $o, dir: $d, config: $c,
                    createdConfig: (if .kitty.config == $c then .kitty.createdConfig else $created end),
                    addedNewline: (if $nl == "keep" and .kitty.config == $c then (.kitty.addedNewline // false)
                                   else ($nl == "true") end),
                    savedThemes: ($saved | split(" ") | map(select(. != "")) | unique)}' \
      --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts" --arg d "$dir" --arg c "$target" \
      --argjson created "$created" --arg nl "$CONFIGFILE_ADDED_NEWLINE" --arg saved "$saved"
    ui_ok "$verb iglass for kitty ($(kitty_glass_label "$opts"), $look$(install_summary "$opts"))."
  else
    state_update '.kitty = {version: $v, installedAt: $t, options: $o, dir: $d, config: null,
                    savedThemes: ($saved | split(" ") | map(select(. != "")) | unique)}' \
      --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts" --arg d "$dir" --arg saved "$saved"
    ui_ok "Installed iglass files for kitty."
    ui_warn "Couldn't edit $target (read-only?). Add these two lines to your kitty config:"
    printf '  %s\n  %s\n' "$KITTY_MARKER" "$(kitty_include_line)" >&2
  fi
  if [[ -n "${saved// /}" ]]; then
    ui_info "Your own kitty light/dark theme files are saved and come back with: iglass uninstall"
  fi
  if ! kitty_auto_themes_supported; then
    ui_warn "kitty $(kitty_version) can't switch colors with light and dark mode (kitty $IGLASS_MIN_KITTY_AUTO+ can); using the $(jq -r 'if (.appearance // "auto") == "auto" then "dark" else .appearance end' <<<"$opts") colors."
  fi
  if kitty_running; then
    ui_info "Quit and reopen kitty to apply it (kitty reads transparency only at launch)."
  fi
}

# "blur", or what the user actually gets where blur depends on the desktop.
kitty_glass_label() { # OPTIONS_JSON
  local blur
  read -r _ blur <<<"$(kitty_glass "$1")"
  if [[ "$blur" == 0 ]]; then
    printf 'opaque\n'
  elif is_linux && ! desktop_blurs; then
    printf 'transparency, no blur on this desktop\n'
  else
    printf 'blur\n'
  fi
}

kitty_uninstall() {
  local dir target f removed=0 backups
  dir=$(state_get '.kitty.dir')
  [[ -n "$dir" ]] || dir=$(kitty_config_dir)
  target=$(state_get '.kitty.config')
  if [[ -n "$target" ]]; then
    if configfile_remove_include "$target" "$KITTY_MARKER" "include $dir/iglass.conf" "$(state_get '.kitty.addedNewline')"; then
      if [[ "$(state_get '.kitty.createdConfig')" == true && -f "$target" ]] && ! grep -q '[^[:space:]]' "$target"; then
        rm -f "$target"
      fi
    else
      ui_warn "Couldn't edit $target. Remove the iglass lines from it yourself."
    fi
  fi
  for f in iglass.conf $KITTY_THEME_FILES; do
    if kitty_is_ours "$dir/$f"; then
      rm -f "$dir/$f"
      removed=1
    fi
  done
  # Put back the user's own theme files, unless they made new ones in the meantime.
  backups="$IGLASS_STATE_DIR/backups/kitty-themes"
  for f in $(state_get '.kitty.savedThemes // [] | join(" ")'); do
    if [[ -e "$backups/$f" ]]; then
      if [[ -e "$dir/$f" ]]; then
        ui_warn "Kept your current kitty $f; your earlier one is in $backups."
      else
        mv -f "$backups/$f" "$dir/$f"
      fi
    fi
  done
  rmdir "$dir" 2>/dev/null || true # only when iglass left it empty
  if [[ -n "$(state_get '.kitty')" ]]; then
    state_update 'del(.kitty)'
  fi
  if [[ $removed == 1 || -n "$target" ]]; then
    ui_ok "Removed iglass from kitty."
  elif kitty_present; then
    ui_info "iglass was not installed for kitty."
  fi
}

# Open a new kitty window with a variant's glass (the colors are the installed ones).
kitty_preview() { # OPTIONS_JSON
  local opacity blur app bin
  read -r opacity blur <<<"$(kitty_glass "$1")"
  app=$(kitty_app_path)
  if [[ -n "$app" && -z "${IGLASS_KITTY_BIN:-}" ]]; then
    open -na "$app" --args -o "background_opacity=$opacity" -o "background_blur=$blur"
    return
  fi
  bin=$(kitty_bin)
  [[ -n "$bin" ]] || die "kitty is not installed." "Get it from https://sw.kovidgoyal.net/kitty/"
  detach "$bin" -o "background_opacity=$opacity" -o "background_blur=$blur"
}
