# shellcheck shell=bash
# Warp support: two color themes, and the few Warp settings that make the glass.
#
# Warp reads custom themes from a themes folder and its settings from settings.toml, which it
# watches and applies the moment the file changes (Warp from April 2026 on; older releases
# keep settings elsewhere). iglass writes:
#   <themes>/iglass-dark.yaml, iglass-light.yaml        the colors
# and sets these in settings.toml, leaving every other line as it was:
#   [appearance.themes]  theme, system_theme, selected_system_themes   the colors, light/dark
#   [appearance.window]  override_opacity, override_blur (macOS)       the glass
#   [appearance.cursor]  cursor_display_type                           unless --cursor keep
#   [appearance.text]    font_name, font_size                          with --font
# The lines it replaced are saved, and uninstall puts them back. When nothing else changed in
# the meantime, the file is restored byte for byte.
#
#            macOS                       Linux
# settings   ~/.warp/settings.toml       $XDG_CONFIG_HOME/warp-terminal/settings.toml
# themes     ~/.warp/themes              $XDG_DATA_HOME/warp-terminal/themes

WARP_BUNDLE_ID="dev.warp.Warp-Stable"
WARP_GEN_MARKER="# Generated by iglass"
WARP_THEME_FILES="iglass-dark.yaml iglass-light.yaml"
WARP_TABLES="appearance.themes appearance.window appearance.cursor appearance.text"
# The Linux app id, for niri window rules.
# shellcheck disable=SC2034  # used by desktop_blur_tip in platform.sh
WARP_APP_ID='^dev\.warp\.Warp$'

warp_settings_file() {
  if is_macos; then
    printf '%s/.warp/settings.toml\n' "$HOME"
  else
    printf '%s/warp-terminal/settings.toml\n' "${XDG_CONFIG_HOME:-$HOME/.config}"
  fi
}

warp_themes_dir() {
  if is_macos; then
    printf '%s/.warp/themes\n' "$HOME"
  else
    printf '%s/warp-terminal/themes\n' "${XDG_DATA_HOME:-$HOME/.local/share}"
  fi
}

# Print the path of Warp.app (macOS only).
warp_app_path() {
  is_macos || return 0
  if [[ -n "${IGLASS_WARP_APP:-}" ]]; then
    [[ -d "$IGLASS_WARP_APP" ]] && printf '%s\n' "$IGLASS_WARP_APP"
    return 0
  fi
  local candidate
  for candidate in "/Applications/Warp.app" "$HOME/Applications/Warp.app"; do
    if [[ -d "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  candidate=$(mdfind "kMDItemCFBundleIdentifier == '$WARP_BUNDLE_ID'" 2>/dev/null | head -n 1)
  [[ -n "$candidate" && -d "$candidate" ]] && printf '%s\n' "$candidate"
  return 0
}

# Print the path of the warp-terminal command (Linux only), or nothing.
warp_bin() {
  is_linux || return 0
  if [[ -n "${IGLASS_WARP_BIN:-}" ]]; then
    [[ -x "$IGLASS_WARP_BIN" ]] && printf '%s\n' "$IGLASS_WARP_BIN"
    return 0
  fi
  if command -v warp-terminal >/dev/null 2>&1; then
    command -v warp-terminal
  elif [[ -x /opt/warpdotdev/warp-terminal/warp ]]; then
    printf '%s\n' /opt/warpdotdev/warp-terminal/warp
  fi
  return 0
}

warp_present() {
  if is_macos; then [[ -n "$(warp_app_path)" ]]; else [[ -n "$(warp_bin)" ]]; fi
}

# Print Warp's version, e.g. 0.2026.10.15.08.12.stable_01 (macOS; Linux builds don't report it).
warp_version() {
  local app v
  app=$(warp_app_path)
  [[ -n "$app" ]] || return 0
  v=$(plutil -extract WarpVersion raw -o - "$app/Contents/Info.plist" 2>/dev/null) ||
    v=$(plutil -extract CFBundleShortVersionString raw -o - "$app/Contents/Info.plist" 2>/dev/null) || true
  printf '%s\n' "${v#v}"
}

# Print the path of the settings schema Warp ships with settings.toml support, or nothing.
warp_schema() {
  local app bin dir candidate
  if is_macos; then
    app=$(warp_app_path)
    [[ -n "$app" ]] && candidate="$app/Contents/Resources/settings_schema.json"
  else
    bin=$(warp_bin)
    if [[ -n "$bin" ]]; then
      dir=$(cd "$(dirname "$bin")" && pwd -P)
      [[ -L "$bin" ]] && dir=$(cd "$(dirname "$bin")" && cd "$(dirname "$(readlink "$bin")")" && pwd -P)
      candidate="$dir/resources/settings_schema.json"
      [[ -f "$candidate" ]] || candidate=/opt/warpdotdev/warp-terminal/resources/settings_schema.json
    fi
  fi
  [[ -n "${candidate:-}" && -f "$candidate" ]] && printf '%s\n' "$candidate"
  return 0
}

# warp_validate SETTINGS_TSV — check every setting iglass writes against the schema of the
# installed Warp, so a renamed setting is caught before anything changes. Prints the settings
# Warp doesn't know. Skipped when Warp's schema isn't found.
warp_validate() {
  local schema unknown
  schema=$(warp_schema)
  [[ -n "$schema" ]] || return 0
  unknown=$(cut -f1,2 "$1" | jq -Rr --slurpfile s "$schema" '
    split("\t") as [$table, $key]
    | select($s[0] | reduce ($table | split(".") + [$key])[] as $p (.; .properties[$p]? // null) | . == null)
    | "\($table).\($key)"') || return 0
  [[ -z "$unknown" ]] && return 0
  printf '%s\n' "$unknown"
  return 1
}

# warp_theme OPTIONS_JSON MODE — print one theme file.
warp_theme() {
  jq -nj --slurpfile palette "$IGLASS_PALETTE" --argjson o "$1" --arg mode "$2" \
    -f "$IGLASS_ROOT/lib/warp.jq"
}

# warp_glass OPTIONS_JSON — print "OPACITY BLUR" for Warp: opacity in percent (1–100), blur
# radius (0 = none) for the chosen variant or custom settings.
warp_glass() {
  jq -nr --slurpfile palette "$IGLASS_PALETTE" --argjson o "$1" '
    $palette[0] as $p
    | (if $o.custom then $p.variants[$o.custom.base] + $o.custom.overrides else $p.variants[$o.variant] end) as $v
    | "\([(1 - $v.transparency) * 100 | round, 1] | max) \(if ($v.blur | not) then 0 else $v.blurRadius end)"'
}

# warp_settings OPTIONS_JSON [THEMES_DIR] — print the settings iglass sets, as tab-separated
# TABLE KEY LINE rows. Theme paths are absolute, or without THEMES_DIR relative to Warp's themes
# folder (how Warp itself writes them). Blur is a macOS-only Warp setting.
warp_settings() {
  local opacity blur
  read -r opacity blur <<<"$(warp_glass "$1")"
  jq -nr --argjson o "$1" --arg dir "${2:-}" --arg opacity "$opacity" --arg blur "$blur" \
    --argjson mac "$(is_macos && echo true || echo false)" '
    def theme($mode): "{ custom = { name = \("iglass \($mode | ascii_upcase[0:1])\($mode[1:])" | tojson), path = \("\(if $dir == "" then "" else $dir + "/" end)iglass-\($mode).yaml" | tojson) } }";
    ($o.appearance // "auto") as $look
    | [
        ["appearance.themes", "theme", "theme = \(theme(if $look == "auto" then "dark" else $look end))"],
        ["appearance.themes", "system_theme", "system_theme = \($look == "auto")"],
        ["appearance.themes", "selected_system_themes",
         "selected_system_themes = { light = \(theme("light")), dark = \(theme("dark")) }"],
        ["appearance.window", "override_opacity", "override_opacity = \($opacity)"]
      ]
      + (if $mac then [["appearance.window", "override_blur", "override_blur = \([($blur | tonumber), 1] | max)"]] else [] end)
      + (if $o.cursor == "keep" then []
         else [["appearance.cursor", "cursor_display_type",
                "cursor_display_type = \({"bar": "bar", "box": "block", "underline": "underline"}[$o.cursor] | tojson)"]] end)
      + (if $o.fontFamily then [["appearance.text", "font_name", "font_name = \($o.fontFamily | tojson)"],
                                ["appearance.text", "font_size", "font_size = \($o.fontSize | tostring | if test("\\.") then . else . + ".0" end)"]]
         else [] end)
    | .[] | join("\t")'
}

# warp_export_dir OPTIONS_JSON DIR — write the two themes and iglass-settings.toml (the settings
# to copy into Warp's settings.toml) into DIR.
warp_export_dir() {
  local opts=$1 dir=$2 mode
  mkdir -p "$dir"
  for mode in dark light; do
    warp_theme "$opts" "$mode" >"$dir/iglass-$mode.yaml"
  done
  {
    printf '%s\n' "# Generated by iglass $(jq -r .version <<<"$opts") (https://github.com/vukkt/iglass): settings for Warp." \
      "# Copy iglass-dark.yaml and iglass-light.yaml into $(warp_themes_dir | sed "s|^$HOME|~|")," \
      "# then merge these lines into $(warp_settings_file | sed "s|^$HOME|~|") (or run: iglass install --terminal warp)."
    local table="" t k line
    while IFS=$'\t' read -r t k line; do
      [[ "$t" == "$table" ]] || printf '\n[%s]\n' "$t"
      table=$t
      printf '%s\n' "$line"
    done < <(warp_settings "$opts")
  } >"$dir/iglass-settings.toml"
}

warp_is_ours() { [[ -f "$1" ]] && grep -q "^$WARP_GEN_MARKER" "$1"; }

# A setting still holds what iglass wrote: the same line, or (for the theme settings, which Warp
# rewrites with paths relative to its themes folder) a reference to an iglass theme.
_warp_still_ours() { # TABLE KEY CURRENT_LINE WRITTEN_LINE
  [[ "$3" == "$4" ]] && return 0
  [[ "$1" == appearance.themes && "$2" != system_theme && "$3" == *iglass-*.yaml* ]]
}

_warp_sum() { [[ -f "$1" ]] && cksum <"$1" | tr -d ' \t'; }

# warp_install OPTIONS_JSON
warp_install() {
  local opts=$1 settings themes work rows edits problem unknown f mode verb=Installed look
  local prev wrote created_file=false table key line old t k
  [[ -n "$(state_get '.warp.installedAt')" ]] && verb=Updated
  settings=$(warp_settings_file)
  themes=$(warp_themes_dir)

  problem=$(toml_layout_problem "$settings" "$WARP_TABLES")
  if [[ -n "$problem" ]]; then
    die "Your Warp settings set this in a way iglass doesn't edit: $problem" \
      "Put it under its [table] header the way Warp writes it (e.g. [appearance.window] then override_opacity = 80), then run iglass install again. Nothing was changed."
  fi

  mkdir -p "$IGLASS_STATE_DIR"
  work=$(mktemp -d "$IGLASS_STATE_DIR/.warp.XXXXXX") || die "Could not create a temporary folder."
  for mode in dark light; do
    warp_theme "$opts" "$mode" >"$work/iglass-$mode.yaml"
  done
  rows="$work/settings.tsv"
  warp_settings "$opts" "$themes" >"$rows"
  if ! unknown=$(warp_validate "$rows"); then
    rm -rf "$work"
    die "This Warp doesn't know these settings: $(tr '\n' ' ' <<<"$unknown")Nothing was changed." \
      "Update Warp, or report this at https://github.com/vukkt/iglass/issues"
  fi

  # What each setting held before iglass: kept from the first install, so reinstalling with
  # other options still restores the user's own values.
  prev=$(state_get '.warp.previous // {}')
  [[ -n "$prev" ]] || prev='{}'
  wrote='{}'
  edits="$work/edits.tsv"
  : >"$edits"
  while IFS=$'\t' read -r table key line; do
    if [[ "$(jq -r --arg k "$table $key" 'has($k)' <<<"$prev")" != true ]]; then
      old=$(toml_get "$settings" "$table" "$key")
      prev=$(jq --arg k "$table $key" --arg l "$old" '. + {($k): (if $l == "" then null else $l end)}' <<<"$prev")
    fi
    wrote=$(jq --arg k "$table $key" --arg l "$line" '. + {($k): $l}' <<<"$wrote")
    printf 'set\t%s\t%s\t%s\n' "$table" "$key" "$line" >>"$edits"
  done <"$rows"
  # Settings an earlier install wrote and this one doesn't (e.g. --font keep now): put them back.
  while IFS=$'\t' read -r t k; do
    [[ -n "$t" ]] || continue
    _warp_restore_edit "$settings" "$t" "$k" "$(state_get '.warp.wrote[$k]' --arg k "$t $k")" \
      "$(jq -r --arg k "$t $k" '.[$k] // empty' <<<"$prev")" >>"$edits"
    prev=$(jq --arg k "$t $k" 'del(.[$k])' <<<"$prev")
  done < <(state_read | jq -r --argjson now "$wrote" '.warp.wrote // {} | keys[] | select(. as $k | $now | has($k) | not) | split(" ") | join("\t")')

  if [[ -n "$(state_get '.warp.installedAt')" ]]; then
    created_file=$(state_get '.warp.createdFile == true | tostring')
  elif [[ ! -e "$settings" ]]; then
    created_file=true
  fi
  # Tables iglass adds, so uninstall can remove their headers again.
  local created_tables
  created_tables=$(state_get '.warp.createdTables // []')
  [[ -n "$created_tables" ]] || created_tables='[]'
  for t in $WARP_TABLES; do
    if grep -q "^$t	" "$rows" && ! grep -q "^[[:space:]]*\[[[:space:]]*${t}[[:space:]]*\]" "$settings" 2>/dev/null; then
      created_tables=$(jq --arg t "$t" '. + [$t] | unique' <<<"$created_tables")
    fi
  done

  # Back up the settings file once, before iglass first changes it.
  if [[ -f "$settings" && ! -f "$IGLASS_STATE_DIR/backups/warp-settings-before-iglass.toml" ]] &&
    [[ -z "$(state_get '.warp.installedAt')" ]]; then
    mkdir -p "$IGLASS_STATE_DIR/backups"
    cp "$settings" "$IGLASS_STATE_DIR/backups/warp-settings-before-iglass.toml"
  fi

  mkdir -p "$themes" || { rm -rf "$work"; die "Could not create $themes."; }
  for f in $WARP_THEME_FILES; do
    if [[ -e "$themes/$f" ]] && ! warp_is_ours "$themes/$f"; then
      mkdir -p "$IGLASS_STATE_DIR/backups"
      mv -f "$themes/$f" "$IGLASS_STATE_DIR/backups/$f.$(date +%Y%m%d%H%M%S)"
      ui_warn "Moved a Warp theme that wasn't iglass's aside: $themes/$f → $IGLASS_STATE_DIR/backups"
    fi
    mv -f "$work/$f" "$themes/$f"
  done

  for t in $(jq -r '.[]' <<<"$created_tables"); do
    printf 'drop\t%s\n' "$t" >>"$edits" # emptied by a setting put back above
  done

  look=$(jq -r 'if (.appearance // "auto") == "auto" then "light and dark, " else "" end' <<<"$opts")
  toml_edit "$settings" "$work/settings.toml" "$edits"
  # The record comes first: if iglass is stopped halfway, uninstall still knows what to undo.
  local old_record
  old_record=$(state_read | jq -c '.warp // null')
  state_update '.warp = {version: $v, installedAt: $t, options: $o, settings: $s, themes: $th,
                  previous: $prev, wrote: $wrote, createdTables: $ct, createdFile: $cf, sum: $sum}' \
    --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts" --arg s "$settings" --arg th "$themes" \
    --argjson prev "$prev" --argjson wrote "$wrote" --argjson ct "$created_tables" \
    --argjson cf "$created_file" --arg sum "$(_warp_sum "$work/settings.toml")"
  mkdir -p "$(dirname "$settings")" 2>/dev/null
  if [[ ! -w "$(dirname "$settings")" ]] || { [[ -e "$settings" ]] && [[ ! -w "$settings" ]]; } ||
    ! configfile_rewrite "$settings" "$work/settings.toml"; then
    # Settings unchanged: keep what an earlier install recorded, or record the themes alone.
    state_update '.warp = (if $old.settings then $old else {settings: null, themes: $th} end)
                    + {version: $v, installedAt: $t, options: $o}' \
      --argjson old "$old_record" --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts" --arg th "$themes"
    ui_ok "Installed iglass themes for Warp."
    ui_warn "Couldn't edit $settings (read-only?). Add these settings to it:"
    cut -f3 "$rows" | sed 's/^/  /' >&2
    rm -rf "$work"
    return 0
  fi
  rm -rf "$work"
  ui_ok "$verb iglass for Warp ($(warp_glass_label "$opts"), $look$(install_summary "$opts")). Warp applies it right away."
  if [[ -z "$(warp_schema)" ]]; then
    ui_warn "Couldn't find Warp's settings schema, so this Warp may be older than April 2026 and not read settings.toml yet. If nothing changed, update Warp."
  fi
}

# _warp_restore_edit FILE TABLE KEY WRITTEN PREVIOUS — print the edit that puts back the user's
# own setting, unless they changed it since iglass wrote it.
_warp_restore_edit() {
  local current
  current=$(toml_get "$1" "$2" "$3")
  if [[ -n "$current" ]] && ! _warp_still_ours "$2" "$3" "$current" "$4"; then
    ui_warn "Kept your own Warp setting: $current" >&2
    return 0
  fi
  if [[ -n "$5" ]]; then
    printf 'set\t%s\t%s\t%s\n' "$2" "$3" "$5"
  else
    printf 'unset\t%s\t%s\n' "$2" "$3"
  fi
}

# "blur", or what the user actually gets.
warp_glass_label() { # OPTIONS_JSON
  local opacity blur
  read -r opacity blur <<<"$(warp_glass "$1")"
  if [[ "$opacity" == 100 ]]; then
    printf 'opaque\n'
  elif is_linux && ! desktop_blurs warp; then
    printf 'transparency, no blur on this desktop\n'
  elif [[ "$blur" == 0 ]]; then
    printf 'transparency\n'
  else
    printf 'blur\n'
  fi
}

warp_uninstall() {
  local settings themes f removed=0 backup work edits t k
  settings=$(state_get '.warp.settings')
  themes=$(state_get '.warp.themes')
  [[ -n "$themes" ]] || themes=$(warp_themes_dir)
  backup="$IGLASS_STATE_DIR/backups/warp-settings-before-iglass.toml"
  if [[ -n "$settings" ]]; then
    removed=1
    if [[ -f "$settings" && "$(_warp_sum "$settings")" == "$(state_get '.warp.sum')" ]]; then
      # Unchanged since iglass wrote it: put the original back exactly.
      if [[ "$(state_get '.warp.createdFile')" == true ]]; then
        rm -f "$settings"
      elif [[ -f "$backup" ]]; then
        configfile_rewrite "$settings" "$backup" || ui_warn "Couldn't restore $settings; your original is in $backup."
      fi
    elif [[ -f "$settings" ]]; then
      # Changed since (Warp or the user saved settings): restore only iglass's settings.
      mkdir -p "$IGLASS_STATE_DIR"
      work=$(mktemp -d "$IGLASS_STATE_DIR/.warp.XXXXXX") || die "Could not create a temporary folder."
      edits="$work/edits.tsv"
      : >"$edits"
      while IFS=$'\t' read -r t k; do
        [[ -n "$t" ]] || continue
        _warp_restore_edit "$settings" "$t" "$k" "$(state_get '.warp.wrote[$k]' --arg k "$t $k")" \
          "$(state_get '.warp.previous[$k]' --arg k "$t $k")" >>"$edits"
      done < <(state_get '.warp.wrote // {} | keys[] | split(" ") | join("\t")')
      for t in $(state_get '.warp.createdTables // [] | join(" ")'); do
        printf 'drop\t%s\n' "$t" >>"$edits"
      done
      toml_edit "$settings" "$work/settings.toml" "$edits"
      if [[ "$(state_get '.warp.createdFile')" == true ]] && ! grep -q '[^[:space:]]' "$work/settings.toml"; then
        rm -f "$settings"
      elif ! configfile_rewrite "$settings" "$work/settings.toml"; then
        ui_warn "Couldn't edit $settings. Remove iglass's settings from it yourself."
      fi
      rm -rf "$work"
    fi
  fi
  for f in $WARP_THEME_FILES; do
    if warp_is_ours "$themes/$f"; then
      rm -f "$themes/$f"
      removed=1
    fi
  done
  # Folders only iglass's files were in (Warp creates them again when it needs them).
  rmdir "$themes" 2>/dev/null || true
  rmdir "$(dirname "$themes")" 2>/dev/null || true
  [[ -z "$settings" ]] || rmdir "$(dirname "$settings")" 2>/dev/null || true
  rm -f "$backup"
  if [[ -n "$(state_get '.warp')" ]]; then
    state_update 'del(.warp)'
  fi
  if [[ $removed == 1 ]]; then
    ui_ok "Removed iglass from Warp."
  elif warp_present; then
    ui_info "iglass was not installed for Warp."
  fi
}
