# shellcheck shell=bash
# Ghostty support: theme files, an iglass config file, and one include line in the user's config.
#
# Ghostty reads, in order (later files win):
#   $XDG_CONFIG_HOME/ghostty/config.ghostty, …/config,
#   ~/Library/Application Support/com.mitchellh.ghostty/config.ghostty, …/config  (macOS only)
# iglass writes its themes to $XDG_CONFIG_HOME/ghostty/themes/iglass-<variant>-<mode>, its settings
# to $XDG_CONFIG_HOME/ghostty/iglass.ghostty, and adds two lines (a comment and an optional
# `config-file` include) to the config file Ghostty loads last, so iglass takes effect there.
# Uninstall removes exactly those two lines.

GHOSTTY_BUNDLE_ID="com.mitchellh.ghostty"
GHOSTTY_MARKER="# Added by iglass (https://github.com/vukkt/iglass). Remove with: iglass uninstall"
GHOSTTY_THEME_MARKER="# Generated by iglass"

ghostty_xdg_dir() {
  printf '%s\n' "${IGLASS_GHOSTTY_XDG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/ghostty}"
}

ghostty_appsupport_dir() {
  printf '%s\n' "${IGLASS_GHOSTTY_APPSUPPORT_DIR:-$HOME/Library/Application Support/$GHOSTTY_BUNDLE_ID}"
}

ghostty_themes_dir() { printf '%s/themes\n' "$(ghostty_xdg_dir)"; }
ghostty_iglass_file() { printf '%s/iglass.ghostty\n' "$(ghostty_xdg_dir)"; }

# Print the path of Ghostty.app (macOS only).
ghostty_app_path() {
  is_macos || return 0
  if [[ -n "${IGLASS_GHOSTTY_APP:-}" ]]; then
    [[ -d "$IGLASS_GHOSTTY_APP" ]] && printf '%s\n' "$IGLASS_GHOSTTY_APP"
    return 0
  fi
  local candidate
  for candidate in "/Applications/Ghostty.app" "$HOME/Applications/Ghostty.app"; do
    if [[ -d "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  candidate=$(mdfind "kMDItemCFBundleIdentifier == '$GHOSTTY_BUNDLE_ID'" 2>/dev/null | head -n 1)
  [[ -n "$candidate" && -d "$candidate" ]] && printf '%s\n' "$candidate"
  return 0
}

ghostty_version() {
  local app bin
  if is_linux; then
    bin=$(ghostty_bin)
    [[ -n "$bin" ]] || return 0
    "$bin" --version 2>/dev/null | sed -n '1s/^Ghostty \([0-9][0-9.]*\).*/\1/p'
    return 0
  fi
  app=$(ghostty_app_path)
  [[ -n "$app" ]] || return 0
  plutil -extract CFBundleShortVersionString raw -o - "$app/Contents/Info.plist" 2>/dev/null || true
}

# Print the path of the ghostty executable, or nothing if Ghostty is not installed.
ghostty_bin() {
  local app
  if is_linux; then
    if [[ -n "${IGLASS_GHOSTTY_BIN:-}" ]]; then
      [[ -x "$IGLASS_GHOSTTY_BIN" ]] && printf '%s\n' "$IGLASS_GHOSTTY_BIN"
    else
      command -v ghostty 2>/dev/null
    fi
    return 0
  fi
  app=$(ghostty_app_path)
  [[ -n "$app" && -x "$app/Contents/MacOS/ghostty" ]] && printf '%s\n' "$app/Contents/MacOS/ghostty"
  return 0
}

ghostty_present() {
  [[ -n "$(ghostty_bin)" ]] || [[ -n "$(ghostty_app_path)" ]]
}

ghostty_running() {
  proc_running ghostty
}

# Config files Ghostty loads, in load order (later wins).
ghostty_config_candidates() {
  local xdg as
  xdg=$(ghostty_xdg_dir)
  printf '%s\n' "$xdg/config.ghostty" "$xdg/config"
  is_macos || return 0
  as=$(ghostty_appsupport_dir)
  printf '%s\n' "$as/config.ghostty" "$as/config"
}

# The config file iglass should include itself from: the last one Ghostty loads. When none
# exists, the XDG one with the file name this Ghostty version reads.
ghostty_target_config() {
  local f last=""
  while IFS= read -r f; do
    [[ -e "$f" ]] && last=$f
  done < <(ghostty_config_candidates)
  if [[ -n "$last" ]]; then
    printf '%s\n' "$last"
  elif version_ge "$(ghostty_version)" 1.2.3; then
    printf '%s/config.ghostty\n' "$(ghostty_xdg_dir)"
  else
    printf '%s/config\n' "$(ghostty_xdg_dir)"
  fi
}

ghostty_include_line() {
  printf 'config-file = ?"%s"\n' "$(ghostty_iglass_file)"
}

# True when FILE contains iglass's include lines.
ghostty_has_include() {
  [[ -f "$1" ]] && grep -qxF "$GHOSTTY_MARKER" "$1" && grep -qxF "$(ghostty_include_line)" "$1"
}

# ghostty_validate DIR — validate DIR/iglass.ghostty with DIR/themes, isolated from the user's
# own config (Ghostty's validator also loads the default config files, so it runs with HOME
# pointed at a scratch folder). Prints Ghostty's messages on failure. Skipped without Ghostty.
ghostty_validate() {
  local dir=$1 bin home out
  bin=$(ghostty_bin)
  [[ -n "$bin" ]] || return 0
  home="$dir/.home"
  mkdir -p "$home/.config/ghostty"
  cp -R "$dir/themes" "$home/.config/ghostty/themes"
  cp "$dir/iglass.ghostty" "$home/.config/ghostty/config.ghostty"
  if ! out=$(HOME="$home" XDG_CONFIG_HOME="$home/.config" "$bin" +validate-config 2>&1); then
    printf '%s\n' "$out" >&2
    return 1
  fi
}

# Decide between Ghostty's native Liquid Glass and a classic blur radius. Liquid Glass is a
# macOS material, so Linux always gets blur.
ghostty_glass_mode() { # REQUESTED(auto|native|blur)
  if is_linux; then
    # --glass native only gets here from export (files for a Mac); see _validate_look_options.
    if [[ "$1" == native ]]; then printf 'native\n'; else printf 'blur\n'; fi
    return
  fi
  case "$1" in
    native | blur) printf '%s\n' "$1" ;;
    *)
      if version_ge "$(macos_version)" 26 && ghostty_supports_native_glass; then
        printf 'native\n'
      else
        printf 'blur\n'
      fi
      ;;
  esac
}

# Ghostty added the macos-glass-* blur values in a recent release; ask it rather than guessing.
ghostty_supports_native_glass() {
  local bin tmp ok=1
  bin=$(ghostty_bin)
  [[ -n "$bin" ]] || return 1
  mkdir -p "$IGLASS_STATE_DIR" 2>/dev/null
  tmp=$(mktemp -d "$IGLASS_STATE_DIR/.ghostty-probe.XXXXXX") || return 1
  mkdir -p "$tmp/.config/ghostty"
  printf 'background-blur = macos-glass-regular\n' >"$tmp/.config/ghostty/config.ghostty"
  if HOME="$tmp" XDG_CONFIG_HOME="$tmp/.config" "$bin" +validate-config >/dev/null 2>&1; then
    ok=0
  fi
  rm -rf "$tmp"
  return $ok
}

# ghostty_theme OPTIONS_JSON MODE WHICH — print one theme file.
ghostty_theme() {
  jq -nj --slurpfile palette "$IGLASS_PALETTE" --argjson o "$1" --arg mode "$2" --arg which "$3" \
    -f "$IGLASS_ROOT/lib/ghostty.jq"
}

# ghostty_settings OPTIONS_JSON — print iglass.ghostty (theme selection, padding, cursor, font).
ghostty_settings() {
  jq -nr --argjson o "$1" '
    (if $o.custom then "custom" else $o.variant end) as $t
    | [
        "# iglass settings for Ghostty, generated by iglass \($o.version). `iglass install` rewrites this file.",
        "theme = light:iglass-\($t)-light,dark:iglass-\($t)-dark",
        "window-padding-x = 12",
        "window-padding-y = 10",
        "window-padding-balance = true"
      ]
      + (if $o.cursor == "keep" then []
         else ["cursor-style = \({"bar": "bar", "box": "block", "underline": "underline"}[$o.cursor])",
               "cursor-style-blink = true"] end)
      + (if $o.window == "no-titlebar"
         then [if $o.platform == "linux" then "gtk-titlebar = false" else "macos-titlebar-style = hidden" end]
         else [] end)
      + (if $o.fontFamily then ["font-family = \"\($o.fontFamily)\"", "font-size = \($o.fontSize)"] else [] end)
    | join("\n")'
}

# ghostty_export_dir OPTIONS_JSON DIR — write themes/ and iglass.ghostty into DIR.
ghostty_export_dir() {
  local opts=$1 dir=$2 which mode
  mkdir -p "$dir/themes"
  for which in $(palette_query '.variantOrder | join(" ")') $(jq -r 'if .custom then "custom" else empty end' <<<"$opts"); do
    for mode in dark light; do
      ghostty_theme "$opts" "$mode" "$which" >"$dir/themes/iglass-$which-$mode"
    done
  done
  ghostty_settings "$opts" >"$dir/iglass.ghostty"
}

# Write FILE's new CONTENT without breaking a symlinked dotfile: edit the link's target, keep
# its permissions, replace it atomically.
_ghostty_rewrite() { # FILE CONTENT_FILE
  local file=$1 content=$2 real dir tmp mode
  real=$file
  if [[ -L "$file" ]]; then
    real=$(cd "$(dirname "$file")" && cd "$(dirname "$(readlink "$file")")" && pwd)/$(basename "$(readlink "$file")")
  fi
  dir=$(dirname "$real")
  tmp=$(mktemp "$dir/.iglass-config.XXXXXX") || return 1
  cat "$content" >"$tmp" || { rm -f "$tmp"; return 1; }
  if [[ -f "$real" ]]; then
    mode=$(file_mode "$real")
    chmod "${mode:-644}" "$tmp"
  else
    chmod 644 "$tmp"
  fi
  mv -f "$tmp" "$real"
}

# Add iglass's include to the user's config. Returns 1 (and prints instructions) when the
# file can't be written, e.g. a read-only config managed by Nix or home-manager.
GHOSTTY_ADDED_NEWLINE=keep # set by ghostty_add_include: true, false, or keep (already there)

ghostty_add_include() {
  local target=$1 tmp backup_dir
  GHOSTTY_ADDED_NEWLINE=keep
  ghostty_has_include "$target" && return 0
  GHOSTTY_ADDED_NEWLINE=false
  mkdir -p "$(dirname "$target")" 2>/dev/null
  if [[ -f "$target" ]]; then
    backup_dir="$IGLASS_STATE_DIR/backups"
    mkdir -p "$backup_dir"
    [[ -f "$backup_dir/ghostty-config-before-iglass" ]] ||
      cp "$target" "$backup_dir/ghostty-config-before-iglass"
  fi
  tmp=$(mktemp "$IGLASS_STATE_DIR/.ghostty-config.XXXXXX") || return 1
  if [[ -s "$target" ]]; then
    cat "$target" >"$tmp"
    if [[ -n "$(tail -c 1 "$target")" ]]; then # file lacked a final newline
      printf '\n' >>"$tmp"
      GHOSTTY_ADDED_NEWLINE=true
    fi
    printf '\n' >>"$tmp"
  fi
  printf '%s\n%s\n' "$GHOSTTY_MARKER" "$(ghostty_include_line)" >>"$tmp"
  if [[ ! -w "$(dirname "$target")" ]] || { [[ -e "$target" ]] && [[ ! -w "$target" ]]; } ||
    ! _ghostty_rewrite "$target" "$tmp"; then
    rm -f "$tmp"
    return 1
  fi
  rm -f "$tmp"
}

# Remove iglass's two lines (and the blank line iglass added before them). STRIP_NEWLINE=true
# drops the final newline iglass added to a file that had none, if iglass's lines were last.
ghostty_remove_include() {
  local target=$1 strip=${2:-false} tmp
  ghostty_has_include "$target" || return 0
  tmp=$(mktemp "$IGLASS_STATE_DIR/.ghostty-config.XXXXXX") || return 1
  # Not "include": that's a reserved word in gawk, the awk on Fedora and Arch.
  if ! awk -v marker="$GHOSTTY_MARKER" -v inc="$(ghostty_include_line)" -v strip="$strip" '
    { lines[NR] = $0 }
    END {
      for (i = 1; i <= NR; i++) {
        if (lines[i] == marker && lines[i + 1] == inc) {
          if (n > 0 && out[n] == "") n--   # the blank separator iglass added
          last = (i + 1 == NR)
          i++
          continue
        }
        out[++n] = lines[i]
        last = 0
      }
      for (i = 1; i <= n; i++) printf "%s%s", out[i], (i < n || !(strip == "true" && last) ? "\n" : "")
    }' "$target" >"$tmp"; then
    rm -f "$tmp" # never replace the user's config with a half-written one
    return 1
  fi
  _ghostty_rewrite "$target" "$tmp"
  rm -f "$tmp"
}

# ghostty_install OPTIONS_JSON
ghostty_install() {
  local opts=$1 work themes target f created=false verb=Installed glass
  [[ -n "$(state_get '.ghostty.installedAt')" ]] && verb=Updated
  glass=$(jq -r 'if .glass == "native" then "real Liquid Glass" else "blur" end' <<<"$opts")
  if is_linux && ! desktop_blurs; then glass="transparency, no blur on this desktop"; fi
  mkdir -p "$IGLASS_STATE_DIR"
  work=$(mktemp -d "$IGLASS_STATE_DIR/.ghostty.XXXXXX") || die "Could not create a temporary folder."
  ghostty_export_dir "$opts" "$work"
  if ! ghostty_validate "$work"; then
    rm -rf "$work"
    die "Internal error: Ghostty rejected the generated settings. Nothing was changed." \
      "Please report this at https://github.com/vukkt/iglass/issues"
  fi

  themes=$(ghostty_themes_dir)
  mkdir -p "$themes" || die "Could not create $themes."
  # Remove themes from an earlier install that this one doesn't produce (e.g. a custom pair).
  for f in "$themes"/iglass-*; do
    [[ -f "$f" ]] || continue
    if [[ ! -f "$work/themes/$(basename "$f")" ]] && grep -q "^$GHOSTTY_THEME_MARKER" "$f"; then
      rm -f "$f"
    fi
  done
  for f in "$work"/themes/*; do
    mv -f "$f" "$themes/$(basename "$f")"
  done
  mv -f "$work/iglass.ghostty" "$(ghostty_iglass_file)"
  rm -rf "$work"

  target=$(ghostty_target_config)
  [[ -e "$target" ]] || created=true
  if ghostty_add_include "$target"; then
    state_update '.ghostty = {version: $v, installedAt: $t, options: $o, config: $c,
                    createdConfig: (if .ghostty.config == $c then .ghostty.createdConfig else $created end),
                    addedNewline: (if $nl == "keep" and .ghostty.config == $c then (.ghostty.addedNewline // false)
                                   else ($nl == "true") end)}' \
      --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts" --arg c "$target" \
      --argjson created "$created" --arg nl "$GHOSTTY_ADDED_NEWLINE"
    ui_ok "$verb iglass for Ghostty ($glass, $(install_summary "$opts"))."
  else
    state_update '.ghostty = {version: $v, installedAt: $t, options: $o, config: null}' \
      --arg v "$IGLASS_VERSION" --arg t "$(now_iso)" --argjson o "$opts"
    ui_ok "Installed iglass themes for Ghostty."
    ui_warn "Couldn't edit $target (read-only?). Add these two lines to your Ghostty config:"
    printf '  %s\n  %s\n' "$GHOSTTY_MARKER" "$(ghostty_include_line)" >&2
  fi
  if ghostty_running; then
    ui_info "Quit and reopen Ghostty to apply it (Ghostty reads transparency only at launch)."
  fi
}

ghostty_installed() {
  [[ -f "$(ghostty_iglass_file)" ]] || [[ -n "$(state_get '.ghostty.installedAt')" ]]
}

ghostty_uninstall() {
  local target f removed=0
  target=$(state_get '.ghostty.config')
  if [[ -n "$target" ]]; then
    if ghostty_remove_include "$target" "$(state_get '.ghostty.addedNewline')"; then
      # Delete a config file iglass created that now holds nothing else.
      if [[ "$(state_get '.ghostty.createdConfig')" == true && -f "$target" ]] &&
        ! grep -q '[^[:space:]]' "$target"; then
        rm -f "$target"
      fi
    else
      ui_warn "Couldn't edit $target. Remove the iglass lines from it yourself."
    fi
  fi
  for f in "$(ghostty_themes_dir)"/iglass-*; do
    if [[ -f "$f" ]] && grep -q "^$GHOSTTY_THEME_MARKER" "$f"; then
      rm -f "$f"
      removed=1
    fi
  done
  if [[ -f "$(ghostty_iglass_file)" ]]; then
    rm -f "$(ghostty_iglass_file)"
    removed=1
  fi
  # Folders iglass may have created; rmdir only removes them when empty.
  rmdir "$(ghostty_themes_dir)" 2>/dev/null || true
  rmdir "$(ghostty_xdg_dir)" 2>/dev/null || true
  if [[ -n "$(state_get '.ghostty')" ]]; then
    state_update 'del(.ghostty)'
  fi
  if [[ $removed == 1 || -n "$target" ]]; then
    ui_ok "Removed iglass from Ghostty."
  else
    ui_info "iglass was not installed for Ghostty."
  fi
}

# Open a new Ghostty window showing a variant.
ghostty_preview() { # VARIANT
  local app bin
  if is_linux; then
    bin=$(ghostty_bin)
    [[ -n "$bin" ]] || die "Ghostty is not installed." "Get it from https://ghostty.org/download"
    detach "$bin" "--theme=light:iglass-$1-light,dark:iglass-$1-dark"
    return
  fi
  app=$(ghostty_app_path)
  [[ -n "$app" ]] || die "Ghostty is not installed." "Get it from https://ghostty.org"
  open -na "$app" --args "--theme=light:iglass-$1-light,dark:iglass-$1-dark"
}
